/* Dynamic backend messages: French regex → (key, captured var names). Runs
after the exact pass; in French it is an identity transform by construction. */
const BACKEND_REGEX: [RegExp, I18nKey, string[]][] = [
  [/Modèle (.+?) inaccessible \(HTTP (\d+)\)\./g, 'err.repModel', ['m', 'c']],
  [/MusicGen : prédiction (.+?)\./g, 'err.repPredFailed', ['Detail']],
  [/MP3 impossible : (.+?)\./g, 'err.mp3Failed', ['Detail']],
  [/Transcription : HTTP (\d+)\./g, 'err.voiceHttp', ['code']],
  [/SAM : (.+)/g, 'err.samError', ['Detail']],
];

const LANG_KEY = 'mgh_lang';

function isLang(v: unknown): v is Lang {
  return v === 'en' || v === 'fr' || v === 'es' || v === 'de' || v === 'it';
}

export function getLangSnapshot(): Lang {
  if (typeof window === 'undefined') return 'en';
  const v = window.localStorage.getItem(LANG_KEY);
  return isLang(v) ? v : 'en';
}

type Listener = () => void;
const listeners = new Set<Listener>();

export function subscribeLang(fn: Listener): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

export function setLang(lang: Lang): void {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn());
}

/** Eager lookup with the current language (errors thrown outside render). */
export function tr(key: I18nKey, vars?: I18nVars): string {
  return translate(getLangSnapshot(), key, vars);
}

/** Translate a possibly backend-French message for display. Never throws. */
export function translateError(msg: string): string {
  const lang = getLangSnapshot();
  if (!msg) return msg;
  let out = msg;
  for (const [source, key] of BACKEND_EXACT) {
    if (out.includes(source)) out = out.split(source).join(dicts[lang][key]);
  }
  for (const [rx, key, names] of BACKEND_REGEX) {
    rx.lastIndex = 0;
    out = out.replace(rx, (...args: string[]) => {
      const vars: I18nVars = {};
      names.forEach((name, i) => {
        vars[name] = args[i + 1] ?? '';
      });
      return translate(lang, key, vars);
    });
  }
  return out;
}

